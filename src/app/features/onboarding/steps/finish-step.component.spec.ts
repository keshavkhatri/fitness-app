import { TestBed } from '@angular/core/testing';
import { provideRouter } from '@angular/router';
import { NavController, provideIonicAngular } from '@ionic/angular';

import { BILLING_PROVIDER } from '../../../core/entitlements/billing';
import { PREMIUM_TEST_BILLING } from '../../../core/entitlements/testing/premium-billing';
import { KeyValueStorage } from '../../../core/storage/key-value-storage';
import { MemoryKeyValueStorage } from '../../../core/storage/testing/memory-key-value-storage';
import { CLOCK } from '../../../core/time/clock';
import { PROFILE, THURSDAY } from '../../workout/testing/workout-fixtures';
import { PlanIntentService } from '../../../core/workout/plan-intent.service';
import { FinishStepComponent } from './finish-step.component';

async function render(premium: boolean) {
  const storage = new MemoryKeyValueStorage();
  storage.values.set('fitness.profile', JSON.stringify({ version: 2, profile: PROFILE }));
  TestBed.configureTestingModule({
    providers: [
      provideIonicAngular(),
      provideRouter([]),
      { provide: KeyValueStorage, useValue: storage },
      { provide: CLOCK, useValue: () => THURSDAY },
      ...(premium ? [{ provide: BILLING_PROVIDER, useValue: PREMIUM_TEST_BILLING }] : []),
    ],
  });
  const forward = vi.spyOn(TestBed.inject(NavController), 'navigateForward').mockResolvedValue(true);
  const fixture = TestBed.createComponent(FinishStepComponent);
  await vi.waitFor(async () => {
    await fixture.whenStable();
    fixture.detectChanges();
    expect(fixture.nativeElement.querySelector('[data-testid="plan-preview"]')).not.toBeNull();
  });
  const el = fixture.nativeElement as HTMLElement;
  const detect = async () => {
    await fixture.whenStable();
    fixture.detectChanges();
  };
  return { el, storage, forward, detect, q: (id: string) => el.querySelector<HTMLElement>(`[data-testid="${id}"]`) };
}

describe('first-run plan presentation: generated plan or build my own', () => {
  it('keeps the generated plan as the default Free choice and the plan is made and saved as before', async () => {
    const { q, storage } = await render(false);
    expect(q('plan-preview')!.textContent).toMatch(/exercises · about \d+ min/);
    expect(q('choice-generated')!.textContent).toContain('Use generated plan');
    expect(q('choice-generated')!.textContent).toContain('Free');
    expect(JSON.parse(storage.values.get('fitness.workout-plan')!).plan.custom).toBeUndefined();
  });

  it('"Choose how to train" is a choice: generated by default, "Build my own" (Pro) can be picked', async () => {
    const { q } = await render(false);
    expect(q('choice-generated')!.getAttribute('aria-checked')).toBe('true');
    expect(q('choice-build')!.getAttribute('aria-checked')).toBe('false');
    expect(q('choice-build')!.textContent).toContain('Pro');
    expect(q('choice-build')!.textContent).not.toContain('Premium');
    expect(q('choice-build-note')).toBeNull();
  });

  for (const premium of [false, true]) {
    it(`picking "Build my own" never opens the editor during setup; it is remembered for afterwards (${premium ? 'Pro' : 'Free'})`, async () => {
      const { q, forward, storage } = await render(premium);
      q('choice-build')!.click();
      await vi.waitFor(() => expect(JSON.parse(storage.values.get('stokeform.plan-intent') ?? 'null')).toEqual({ version: 1, intent: 'custom' }));
      expect(forward).not.toHaveBeenCalled();
      expect(TestBed.inject(PlanIntentService).intent()).toBe('custom');
    });
  }

  it('says when it will be set up, and picking the generated plan again forgets the choice', async () => {
    const { q, storage, detect } = await render(false);
    q('choice-build')!.click();
    await detect();
    expect(q('choice-build')!.getAttribute('aria-checked')).toBe('true');
    expect(q('choice-build-note')!.textContent).toContain('after the next two screens');
    q('choice-generated')!.click();
    await detect();
    expect(q('choice-build-note')).toBeNull();
    expect(storage.values.has('stokeform.plan-intent')).toBe(false);
  });
});
